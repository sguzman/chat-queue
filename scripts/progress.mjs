#!/usr/bin/env node
import fs from 'node:fs';
const source=JSON.parse(fs.readFileSync(new URL('../progress.json',import.meta.url),'utf8'));
if(source.schemaVersion!==2||!Array.isArray(source.milestones)||!source.milestones.length)throw Error('Invalid progress schema');
const seen=new Set();let total=0,verified=0,implemented=0;
const summary=[];
const bar=p=>'█'.repeat(Math.floor(p/10))+'░'.repeat(10-Math.floor(p/10));
const pct=(n,t)=>Math.floor(n*100/t);
let md='# 🗺️ Chat Queue roadmap\n\nFirefox Developer Edition first. Independent of [Chat Signals](https://github.com/sguzman/chat-signals) and [Jobflick Bridge](https://github.com/sguzman/jobflick-bridge). Work directly on `main`. No project color: emoji-marked workstreams.\n\n';
md+='## 📊 Progress evidence policy\n\n`progress.json` is the canonical milestone → phase → feature → atomic-task ledger. This document is generated by `node scripts/progress.mjs --write`. Only **verified** tasks count toward completion; **implemented** means code/documentation exists but the full task acceptance gate is pending. Node tests, static checks, and synthetic browser tests are separate from authenticated Firefox Developer Edition acceptance. Never call an untested live site feature complete.\n\n';
for(const m of source.milestones){
  let mt=0,mv=0,mi=0;let section=`### ${m.emoji} ${m.id} — ${m.title}\n\n`;
  if(!Array.isArray(m.phases)||!m.phases.length)throw Error(`Missing phases ${m.id}`);
  for(const phase of m.phases){
    section+=`**${phase.id} · ${phase.title}**\n\n`;
    if(!phase.features?.length)throw Error(`Empty phase ${phase.id}`);
    for(const feature of phase.features){
      section+=`**${feature.title}**\n\n`;
      for(const t of feature.tasks){
        if(seen.has(t.id)||!t.id.startsWith(m.id+'-'))throw Error(`Duplicate/out-of-scope task ${t.id}`);
        seen.add(t.id);mt++;total++;
        if(!['verified','implemented','planned'].includes(t.status))throw Error(`Unknown status ${t.id}`);
        if(t.status!=='planned'&&(!Array.isArray(t.evidence)||!t.evidence.length))throw Error(`Missing evidence ${t.id}`);
        if(t.status==='verified'){mv++;verified++;}
        if(t.status==='implemented'){mi++;implemented++;}
        let symbol=t.status==='verified'?'[x]':t.status==='implemented'?'[~]':'[ ]';
        section+=`- ${symbol} \`${t.id}\` ${t.emoji} ${t.title}${t.status==='implemented'?' _(implemented; acceptance pending)_':''}\n`;
      }
      section+='\n';
    }
  }
  if(!mt)throw Error(`Empty milestone ${m.id}`);
  const mp=pct(mv,mt);
  summary.push({id:m.id,emoji:m.emoji,title:m.title,total:mt,verified:mv,implemented:mi,percent:mp});
  md+=`${section}**${m.id} acceptance:** ${mv}/${mt} verified (${mp}%) · ${bar(mp)} · ${mi} implemented but not accepted.\n\n`;
}
md+='## 🛡️ Non-negotiable gates\n\n**G0: scope and security** — separate repository, no telemetry, strict extension allowlist, no public chat content.\n\n**G1: browser-safe HUD** — installed in disposable Firefox Developer Edition, nonintrusive UI, all three themes, accessible editing and stable persistence.\n\n**G2: trustworthy signals** — identity and epoch attribution, no stale restoration called fresh completion; fail closed on ambiguous state.\n\n**G3: guarded send** — authenticated Firefox Developer Edition proves exact input, at most one send attempt, no draft overwrite, no wrong-chat dispatch and no blind retry.\n\n**G4: external API** — real add-on-to-add-on Firefox tests, least-privilege read/append/control permissions, bounded payloads, revocation and recovery.\n\n**G5: conditional engine** — deterministic bounded rules, no loops, user-authorized recovery and no unverified automatic retry.\n\n**G6: release** — repeatable QA, Mozilla-compatible packaging/signing and public-artifact privacy audit.\n\nSafety gates cannot be bypassed by a high percentage.\n';
const allPct=pct(verified,total);
const header=`**Overall: ${verified}/${total} verified (${allPct}%) · ${bar(allPct)} · ${implemented} implemented awaiting acceptance.**\n\n`;
md=md.replace('## 📊 Progress evidence policy',header+'## 📊 Progress evidence policy');
if(process.argv.includes('--write'))fs.writeFileSync(new URL('../ROADMAP.md',import.meta.url),md);
if(process.argv.includes('--check')){
  if(fs.readFileSync(new URL('../ROADMAP.md',import.meta.url),'utf8')!==md)throw Error('ROADMAP.md out of sync: run node scripts/progress.mjs --write');
}
if(process.argv.includes('--json'))console.log(JSON.stringify({total,verified,implemented,percent:allPct,milestones:summary},null,2));
else console.log(`Verified ${verified}/${total} (${allPct}%); implemented/pending acceptance: ${implemented}`);
